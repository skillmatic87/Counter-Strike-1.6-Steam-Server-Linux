const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const html=fs.readFileSync(path.join(__dirname,'../Configure-Server.html'),'utf8');
const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m=>m[1]);
for (const script of scripts) new vm.Script(script);
const sandbox={TextEncoder,TextDecoder,t:key=>key,globalThis:null};sandbox.globalThis=sandbox;
vm.createContext(sandbox);
vm.runInContext(scripts.find(s=>s.includes('const DEMO = ')),sandbox);
vm.runInContext(`
state.files=new Map(Object.entries(DEMO.files).map(([path,text])=>[path,fileRecord(new TextEncoder().encode(text))]));
state.launcher='Start-CS16.sh';state.catalog=DEMO.maps.map(m=>({...m,installed:true}));
state.model=modelFromFiles();state.base=clone(state.model);
`,sandbox);
const run=code=>JSON.parse(vm.runInContext('JSON.stringify('+code+')',sandbox));
assert.equal(run('state.model.rankScore'),'KillsMinusDeaths');
assert.equal(run('state.model.rankBots'),false);
assert.equal(run('makePlan(state.model).length'),0);
vm.runInContext(`state.model.rankScore='Kills';state.model.rankBots=true;`,sandbox);
const plan=run('makePlan(state.model).map(p=>({path:p.path,text:new TextDecoder().decode(p.after)}))');
assert.equal(plan.length,2);
assert.match(plan.find(p=>p.path.endsWith('csstats.cfg')).text,/csstats_rankbots 1/);
assert.equal(JSON.parse(plan.find(p=>p.path==='settings.local.json').text).RankScore,'Kills');
assert.ok(plan.every(p=>!p.text.includes('sm_rankscore')));
vm.runInContext(`state.model=clone(state.base);state.model.hostname='x";quit';`,sandbox);
assert.throws(()=>vm.runInContext('makePlan(state.model)',sandbox));
assert.match(html,/STEAM_0:\[01\]/);
assert.match(html,/AMXX: Steam ID/);
console.log('Configurator passed: JavaScript syntax, default import, StatsX/scoring changes, injection rejection and Steam-ID UI.');
